// Keep downloaded reports self-contained, including the math fonts (no CDN).
import fs from 'node:fs';
import path from 'node:path';
const directory='node_modules/katex/dist';
let css=fs.readFileSync(path.join(directory,'katex.min.css'),'utf8');
css=css.replace(/src:([^;]+);/g,(_,sources)=>{
 const file=sources.match(/url\((?:["'])?(fonts\/[^)"']+\.woff2)(?:["'])?\)/)?.[1];
 if(!file)throw Error('Expected a WOFF2 font in KaTeX stylesheet');
 return `src:url(data:font/woff2;base64,${fs.readFileSync(path.join(directory,file)).toString('base64')}) format("woff2");`;
});
fs.writeFileSync('app/report-math-css.ts','// Generated by scripts/build-math-assets.mjs from KaTeX (MIT). Do not edit.\nexport const mathCss='+JSON.stringify(css)+';\n');
console.log('Embedded offline KaTeX styles and fonts.');
