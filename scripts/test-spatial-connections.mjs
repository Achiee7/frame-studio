import assert from 'node:assert/strict';
import {auditSpatialConnections,connectSpatialCandidate} from '../app/spatial-connections.ts';
import {validSpatialModel} from '../app/spatial-model.ts';
import {createSpatialRule} from '../app/spatial-sketch.ts';
import {sectionForSpatialMember} from '../app/spatial-analysis-input.ts';

const node=(id,x,y,z)=>({id,x,y,z,joint:'rigid',support:'free'});
const beam=(id,a,b)=>({id,a,b,kind:'beam'});
const load=(id,target,targetId,t,kind='force')=>({id,kind,target,targetId,t,vector:{x:1,y:2,z:3}});
const a=node('A',-2,0,-1),b=node('B',2,0,1),c=node('C',0,-1,1),d=node('D',0,1,-1);
const m=beam('u','A','B'),v=beam('v','C','D');
const section=sectionForSpatialMember(m);
const crossing={nodes:[a,b,c,d],members:[{...m,section},v],loads:[load('F','member','u',.9),load('U','member','v',0,'distributed')]};
const dimensioned=createSpatialRule(crossing,'length',[{type:'member',id:'u'}],Math.sqrt(20));
const before=structuredClone(dimensioned);
const audit=auditSpatialConnections(dimensioned);
assert.equal(audit.components.length,2);
assert.equal(audit.candidates.length,1);
assert.deepEqual(audit.candidates[0].point,{x:0,y:0,z:0});
for(const joint of ['rigid','pin','hinge']){
  const {model,node:middle}=connectSpatialCandidate(dimensioned,audit.candidates[0],joint);
  assert.equal(middle.joint,joint);assert.equal(model.members.length,4);assert.ok(validSpatialModel(model));
  const done=auditSpatialConnections(model);assert.equal(done.components.length,1);assert.equal(done.candidates.length,0);
  assert.equal(done.joined.find(j=>j.node===middle.id).members.length,4);
  assert.equal(model.members.filter(m=>m.section?.name===section.name).length,2);
  assert.deepEqual(model.rules[0].points,dimensioned.rules[0].points);
  assert.equal(model.rules[0].refs[0].segments.length,2);
  assert.equal(model.loads.filter(l=>l.kind==='distributed').length,2);
  assert.ok(Math.abs(model.loads.find(l=>l.id==='F').t-.8)<1e-10);
  assert.throws(()=>connectSpatialCandidate(model,audit.candidates[0],joint),/changed/);
  assert.deepEqual(dimensioned,before);
}
const elevated={...crossing,nodes:[a,b,{...c,z:c.z+.1},{...d,z:d.z+.1}]};
assert.equal(auditSpatialConnections(elevated).candidates.length,0);
const tee={nodes:[a,b,node('E',0,0,0),node('F',0,2,3),node('G',5,2,4)],members:[m,beam('w','E','F')]};
const report=auditSpatialConnections(tee);
assert.deepEqual(report.isolated,['G']);
const touch=report.candidates[0];assert.equal(touch.kind,'nodeOnMember');assert.deepEqual(touch.nodes,['E']);
assert.equal(connectSpatialCandidate(tee,touch,'pin').node.id,'E');
const triple={nodes:[...crossing.nodes,node('E',0,0,-1),node('F',0,0,1)],members:[...crossing.members,beam('w','E','F')]};
const tripleHits=auditSpatialConnections(triple).candidates;
assert.equal(tripleHits.length,1);assert.equal(tripleHits[0].members.length,3);
const separate={nodes:[a,b,c,d,node('E',a.x,a.y+.0005,a.z)],members:[m,beam('w','E','C')],loads:[load('D','node','E',0)]};
const close=auditSpatialConnections(separate).candidates.find(c=>c.kind==='nearNodes');
assert.ok(Math.abs(close.gap-.0005)<1e-12);
const merged=connectSpatialCandidate(separate,close,'hinge');
assert.equal(merged.node.joint,'hinge');assert.equal(merged.model.nodes.length,4);assert.equal(merged.model.loads[0].targetId,merged.node.id);
assert.equal(auditSpatialConnections(merged.model).components.length,1);
const locked={...separate,nodes:separate.nodes.map(n=>({...n,positionLocked:true}))};
assert.throws(()=>connectSpatialCandidate(locked,close,'rigid'),/locked/);
assert.equal(auditSpatialConnections(separate,.0001).candidates.some(c=>c.kind==='nearNodes'),false);
assert.equal(auditSpatialConnections({nodes:[node('A',0,0,0),node('B',.0005,0,0)],members:[m]}).candidates.length,0);
console.log('Passed: 3D crossing and tee repair, true spatial separation, explicit endpoint merge, preserved loads, sketch rules, sections, families, locks and component diagnostics.');
